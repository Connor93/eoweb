// Extracts chosen game-icons slugs from @iconify-json/game-icons into
// public/icons/{slug}.svg (transparent-bg, currentColor path — mask-ready),
// then writes the manifest + CC-BY attribution. Re-run to add/refresh icons.
import { mkdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const set = require('@iconify-json/game-icons/icons.json');

// The slugs used by the shipped demo pubs (keep in sync with the plan's table).
const SLUGS = [
  'enrage',
  'sword-brandish',
  'poison-bottle',
  'bleeding-wound',
  'broken-shield',
  'armor-vest',
  'mace-head',
  'foot-trip',
  'drop-weapon',
  'health-normal',
  'fist',
  'bloody-sword',
  'shield-echoes',
  // Archer skills/statuses (2026-09-01 archer pass)
  'arrow-scope',
  'barbed-arrow',
  'chained-arrow-heads',
  'sight-disabled',
  'archery-target',
  'bullseye',
];

mkdirSync('public/icons', { recursive: true });
const missing = [];
const vendored = [];
const w = set.width ?? 512;
const h = set.height ?? 512;
for (const slug of SLUGS) {
  const icon = set.icons[slug];
  if (!icon) {
    missing.push(slug);
    continue;
  }
  const vw = icon.width ?? w;
  const vh = icon.height ?? h;
  // Standalone, transparent-bg SVG; fill defaults to the path (mask uses alpha).
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${vw} ${vh}">${icon.body}</svg>`;
  writeFileSync(`public/icons/${slug}.svg`, svg);
  vendored.push(slug);
}
if (missing.length) {
  console.error(
    `Unknown game-icons slugs (fix the table): ${missing.join(', ')}`,
  );
  process.exit(1);
}
writeFileSync(
  'src/ui/in-game/hud/skill-icon-manifest.ts',
  '// AUTO-GENERATED by scripts/fetch-skill-icons.mjs — do not edit by hand.\n' +
    'export const SKILL_ICONS: ReadonlySet<string> = new Set([\n' +
    vendored.map((s) => `  '${s}',`).join('\n') +
    '\n]);\n',
);
const info = set.info ?? {};
writeFileSync(
  'public/icons/ATTRIBUTION.md',
  `# Icon attribution\n\nSkill/status icons are from **game-icons.net** (${info.name ?? 'game-icons'}), ` +
    `licensed **CC BY 3.0** (${info.license?.title ?? 'CC BY 3.0'}, ${info.license?.url ?? 'https://creativecommons.org/licenses/by/3.0/'}).\n\n` +
    'Vendored via @iconify-json/game-icons. Icons used:\n\n' +
    vendored.map((s) => `- ${s}`).join('\n') +
    '\n',
);
console.log(`Vendored ${vendored.length} icons + manifest + attribution.`);
