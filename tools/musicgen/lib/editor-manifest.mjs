/**
 * Renders the track list the map editor's Music dropdown is built from.
 *
 * The editor lives in a different repo (the eomap-js fork), so this is
 * generated and vendored across rather than imported -- the same arrangement
 * the vfx-engine uses. Kept as a pure string-builder so it can be tested here
 * without touching the sibling checkout.
 */

export function renderEditorModule(tracks) {
  const entries = tracks
    .map(
      (track) =>
        `  { id: ${track.id}, label: "${track.id} — ${track.title} (${track.slug})" },`,
    )
    .join('\n');

  return `// DO NOT EDIT -- generated by eoweb scripts/sync-editor-music.mjs
// from eoweb/tools/musicgen/tracks/. Re-run that script after adding a track.
//
// Ids must match the .mid files eoweb ships in public/mfx/. A map pointing at
// an id whose file is not in the deployed eoweb build simply plays nothing.

export const MUSIC_TRACKS = [
${entries}
];
`;
}
